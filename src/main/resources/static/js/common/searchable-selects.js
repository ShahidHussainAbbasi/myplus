/**
 * One consistent, SEARCHABLE dropdown for every module dashboard.
 *
 * WHY THIS FILE EXISTS
 * The education dashboard grew a blanket bootstrap-select initialiser inline in its template, so every
 * education dropdown (mkExam, schoolOwnerDD, …) is searchable. No other dashboard got one. The result was
 * an inconsistency users feel immediately: business had 48 <select> elements of which exactly 2 were
 * bootstrap-select and 1 was searchable — so `sellCustomerDD`, a list that grows to every customer the shop
 * has ever served, was a plain scrolling <select> with no way to type a name.
 *
 * Copying the education block into four more templates would have made the next change a five-place edit
 * (and four of them would be missed). It lives here instead, and each dashboard includes it.
 *
 * WHAT IT SKIPS, AND WHY EACH ONE MATTERS
 *  - `.panel-heading`      the OFF-SCREEN nav selects (#registrationType, #purchaseType, #sellType,
 *                          #feeType, …). They are hidden controls driven by main.js, not user-facing
 *                          dropdowns; wrapping them in bootstrap-select would replace the element the
 *                          navigation (and every Cypress `.select(..., {force:true})`) depends on.
 *                          Verified: every nav select in both dashboards carries this class, so the rule is
 *                          structural rather than a list of ids that would drift the moment one is added.
 *  - DataTables internals  the page-length select is generated by DataTables at runtime, inside
 *                          `.dataTables_wrapper`, and the plugin reads/writes it directly.
 *  - `data-no-search`      explicit per-element opt-out, for a dropdown that should stay native.
 *
 * THE DESTROY TRAP (learned the hard way in the education template — kept here so it cannot be relearned):
 * calling `.selectpicker('destroy')` on a plain <select> makes the plugin bridge CONSTRUCT an instance and
 * immediately destroy it, which removes the generated wrapper *together with the original <select>*. That
 * silently deleted every dropdown on page load, and a try/catch hid it. Only ever destroy when an instance
 * actually exists.
 */
(function ($) {
    'use strict';

    // NOTE ON A THRESHOLD: an earlier draft only added the search box once a list had >= 8 options. That
    // is wrong here, and the reason is the very dropdown that prompted this work. `sellCustomerDD` is
    // EMPTY at page load and filled by AJAX, so at init time it has zero options — it would never qualify,
    // which is exactly the bug being fixed. Re-evaluating later would mean destroying and re-initialising
    // pickers on every ajaxComplete (bootstrap-select only reads data-live-search at construction),
    // closing any open dropdown and discarding a half-typed search on a busy screen.
    // So: live search is ALWAYS on, matching the education dashboard whose behaviour prompted the request.

    function shouldSkip($s) {
        var el = $s[0];
        if (!el) return true;
        if ($s.hasClass('panel-heading')) return true;            // off-screen nav selects
        if ($s.is('[data-no-search]')) return true;               // explicit opt-out
        if ($s.closest('.dataTables_wrapper').length) return true; // DataTables owns this one
        if (/_length$/.test(el.name || '') || /_length$/.test(el.id || '')) return true;
        return false;
    }

    /**
     * Initialise (or refresh) every eligible <select> on the page.
     * Safe to call repeatedly — that is how AJAX-populated dropdowns stay in sync.
     */
    function applySearchableSelects(root) {
        var $scope = root ? $(root) : $(document);
        $scope.find('select').each(function () {
            var $s = $(this);
            if (shouldSkip($s)) return;

            // Only destroy a REAL instance — see the destroy trap above.
            if ($s.data('selectpicker')) {
                try { $s.selectpicker('destroy'); } catch (e) {}
            }

            $s.addClass('selectpicker')
              .attr('data-size', '8')
              .attr('data-style', 'btn-default');

            $s.attr('data-live-search', 'true');

            if (this.multiple) {
                $s.attr('data-actions-box', 'true')
                  .attr('data-selected-text-format', 'count > 2');
            }
            if (!$s.attr('title')) $s.attr('title', 'Select…');
        });

        try { $scope.find('.selectpicker').selectpicker(); } catch (e) {}
    }

    window.applySearchableSelects = applySearchableSelects;

    $(function () {
        applySearchableSelects();

        // Most of these dropdowns are filled by AJAX AFTER load, and several populate helpers append
        // <option>s without calling refresh themselves. One ajaxComplete hook keeps every one in sync
        // instead of each helper having to remember.
        // REFRESH ONLY — never a full re-init here. Re-running the initialiser on every AJAX response
        // would destroy and rebuild all ~48 pickers each time, closing whatever the user had open.
        $(document).ajaxComplete(function () {
            try { $('.selectpicker').selectpicker('refresh'); } catch (e) {}
        });
    });
})(jQuery);
