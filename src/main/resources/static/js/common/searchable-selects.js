/**
 * One consistent, SEARCHABLE dropdown for every module dashboard.
 *
 * WHY THIS FILE EXISTS
 * The education dashboard grew a blanket bootstrap-select initialiser inline in its template, so every
 * education dropdown (mkExam, schoolOwnerDD, …) is searchable. No other dashboard got one. The result was
 * an inconsistency users feel immediately: business had 48 <select> elements of which exactly 2 were
 * bootstrap-select and 1 was searchable — so `sellCustomerDD`, a list that grows to every customer the shop
 * has ever served, was a plain scrolling <select> with no way to type a name.
 *
 * Copying the education block into four more templates would have made the next change a five-place edit
 * (and four of them would be missed). It lives here instead, and each dashboard includes it.
 *
 * WHAT IT SKIPS, AND WHY EACH ONE MATTERS
 *  - `.panel-heading`      the OFF-SCREEN nav selects (#registrationType, #purchaseType, #sellType,
 *                          #feeType, …). They are hidden controls driven by main.js, not user-facing
 *                          dropdowns; wrapping them in bootstrap-select would replace the element the
 *                          navigation (and every Cypress `.select(..., {force:true})`) depends on.
 *                          Verified: every nav select in both dashboards carries this class, so the rule is
 *                          structural rather than a list of ids that would drift the moment one is added.
 *  - DataTables internals  the page-length select is generated by DataTables at runtime, inside
 *                          `.dataTables_wrapper`, and the plugin reads/writes it directly.
 *  - `data-no-search`      explicit per-element opt-out, for a dropdown that should stay native.
 *
 * THE DESTROY TRAP (learned the hard way in the education template — kept here so it cannot be relearned):
 * calling `.selectpicker('destroy')` on a plain <select> makes the plugin bridge CONSTRUCT an instance and
 * immediately destroy it, which removes the generated wrapper *together with the original <select>*. That
 * silently deleted every dropdown on page load, and a try/catch hid it. Only ever destroy when an instance
 * actually exists.
 */
(function ($) {
    'use strict';

    // NOTE ON A THRESHOLD: an earlier draft only added the search box once a list had >= 8 options. That
    // is wrong here, and the reason is the very dropdown that prompted this work. `sellCustomerDD` is
    // EMPTY at page load and filled by AJAX, so at init time it has zero options — it would never qualify,
    // which is exactly the bug being fixed. Re-evaluating later would mean destroying and re-initialising
    // pickers on every ajaxComplete (bootstrap-select only reads data-live-search at construction),
    // closing any open dropdown and discarding a half-typed search on a busy screen.
    // So: live search is ALWAYS on, matching the education dashboard whose behaviour prompted the request.

    function shouldSkip($s) {
        var el = $s[0];
        if (!el) return true;
        if ($s.hasClass('panel-heading')) return true;            // off-screen nav selects
        if ($s.is('[data-no-search]')) return true;               // explicit opt-out
        if ($s.closest('.dataTables_wrapper').length) return true; // DataTables owns this one
        if (/_length$/.test(el.name || '') || /_length$/.test(el.id || '')) return true;
        return false;
    }

    /* ── Change tracking (dashboard-freeze fix) ─────────────────────────────────────────────────────────
     *
     * Each picker carries `el.__ssWatch = { mo, dirty, lastVal, io }`:
     *   dirty    its OPTIONS changed (added, removed, relabelled, disabled) since the widget last rebuilt them
     *   lastVal  the selection the widget last showed, so a `.val(x)` from code can be redrawn cheaply
     *   io       its widget is being watched for coming on screen (see deferUntilShown)
     * A MutationObserver sets `dirty`; a signature (count + first/last value) was considered and rejected — it
     * cannot see a relabelled option in the middle of the list, and a wrong customer name on a till is worse
     * than the cost of one observer per select.
     */
    var MO = window.MutationObserver;

    /** A separator no option value contains. Built with fromCharCode so it is VISIBLE in the source: a literal
     *  control character is invisible in a diff (a review read it as no separator at all), and an editor or
     *  tool can silently drop it — which would make ['1','23'] and ['12','3'] both read '123'. */
    var SEP = String.fromCharCode(1);

    function valueKey(el) {
        if (el.multiple) {
            var sel = el.selectedOptions, out = [];
            if (sel) for (var i = 0; i < sel.length; i++) out.push(sel[i].value);
            return out.join(SEP);
        }
        return el.selectedIndex + ':' + el.value;
    }

    /**
     * PSEL-1 — two kinds of change, not one. The <select>'s OWN `disabled` attribute (a `.prop('disabled', …)` from
     * updateReadOnly or the invoice-edit lock) changes nothing a rebuild fixes: the button and the rows need a repaint
     * (checkDisabled + render). Counting it as "options changed" made every lock toggle a full rebuild of the list.
     * Anything else — an option added, removed, relabelled or disabled — is `dirty`, exactly as before.
     */
    function absorb(st, el, records) {
        for (var i = 0; i < records.length; i++) {
            var r = records[i];
            if (r.type === 'attributes' && r.target === el && r.attributeName === 'disabled') st.stateChanged = true;
            else st.dirty = true;
        }
    }

    /** Fold in what the observer has QUEUED but not yet delivered. Its callback runs on a microtask, so a caller that
     *  changed the options one line earlier would otherwise be judged against a stale verdict and get no rebuild. */
    function sync(el) {
        var st = el.__ssWatch;
        if (st && st.mo && st.mo.takeRecords) absorb(st, el, st.mo.takeRecords());
        return st;
    }

    function watch(el, dirty) {
        if (!MO || el.__ssWatch) return el.__ssWatch;
        var st = { dirty: !!dirty, stateChanged: false, lastVal: valueKey(el), mo: null, io: false };
        st.mo = new MO(function (records) { absorb(st, el, records); });
        st.mo.observe(el, { childList: true, subtree: true, characterData: true,
                            attributes: true, attributeFilter: ['value', 'disabled', 'label'] });
        el.__ssWatch = st;
        return st;
    }

    /** The widget now matches the element: forget any change records its own rebuild produced. */
    function markClean(el) {
        var st = el.__ssWatch;
        if (!st) return;
        if (st.mo && st.mo.takeRecords) st.mo.takeRecords();
        st.dirty = false;
        st.stateChanged = false;
        st.lastVal = valueKey(el);
    }

    /* ── Every rebuild counts, not only this file's ─────────────────────────────────────────────────────
     *
     * 45 call sites outside this file call `selectpicker('refresh')` directly (loadUserItems, main.js's form
     * resets, 25 in education.js, …). Each one leaves the widget matching its options — but nothing told the
     * change tracking, so the next pass saw the caller's own option changes, called the picker dirty and rebuilt
     * it a SECOND time. Measured: #sellItemDD, 1,857 options, 2.9 s, still dirty straight after loadUserItems had
     * rebuilt it.
     *
     * bootstrap-select 1.6.2 fires no `refreshed.bs.select` (it triggers only maxReached*), so there is no event
     * to listen for; the plugin function itself is decorated instead. It changes nothing about what a call does —
     * it only records afterwards what that call left true:
     *   refresh                   → the list and the label match the element: clean
     *   construction              → a freshly built widget matches: watched, clean
     *   render / val              → the label matches the selection; the options may still be dirty
     * A bare `.selectpicker()` on an EXISTING instance rebuilds nothing, so it is deliberately not marked clean.
     */
    (function decorate() {
        var orig = $.fn && $.fn.selectpicker;
        if (typeof orig !== 'function' || orig.__ssDecorated) return;
        var decorated = function (cmd) {
            var fresh = (typeof cmd === 'string') ? null
                : this.filter(function () { return this.tagName === 'SELECT' && !$(this).data('selectpicker'); });
            var out = orig.apply(this, arguments);
            try {
                if (cmd === 'refresh') {
                    this.each(function () {
                        if (this.tagName !== 'SELECT' || !$(this).data('selectpicker')) return;
                        watch(this, false);
                        markClean(this);
                    });
                } else if (fresh) {
                    fresh.each(function () {
                        if (!$(this).data('selectpicker')) return;
                        watch(this, false);
                        markClean(this);
                    });
                } else if (cmd === 'render' || (cmd === 'val' && arguments.length > 1)) {
                    this.each(function () { if (this.__ssWatch) this.__ssWatch.lastVal = valueKey(this); });
                }
            } catch (e) {}
            return out;
        };
        for (var k in orig) { if (Object.prototype.hasOwnProperty.call(orig, k)) decorated[k] = orig[k]; }
        decorated.__ssDecorated = true;
        $.fn.selectpicker = decorated;
        patchRender(orig);   // PSEL-1 F1 — see below
    })();

    /* ── PSEL-1 F1 — render() in ONE pass ───────────────────────────────────────────────────────────────
     *
     * This was the New Sale freeze. bootstrap-select 1.6.2's render(updateLi) walks every <option> and calls
     * setDisabled(i) + setSelected(i), and EACH of those runs
     *     this.$lis.filter('[data-original-index="' + i + '"]')
     * — an attribute match across EVERY row, once per option: O(n²). Measured (CDP profile, 2026-09-15,
     * demo.business, 2,511 products): one refresh 8.8 s, of which render 8.5 s; rebuilding the rows themselves
     * (reloadLi + createLi + liHeight) 0.3 s. Self time: jQuery attr 5.9 s + native getAttribute 4.9 s.
     *
     * The replacement indexes every row by data-original-index ONCE, then does for each option exactly what
     * setDisabled/setSelected do — the same predicates (`:disabled` on the option or its parent, `:selected`) and the
     * same jQuery DOM calls — and hands the rest to the library's own render(false), its "rows already right" path
     * (tab index, the button's label and title). Single-row calls (setSelected from a click) are untouched.
     *
     * Feature-detected: a different bootstrap-select (the eventual upgrade) keeps its own render. The original stays
     * reachable as render.__ssOriginal — the gate compares the two outputs byte for byte (sale-picker-speed case 1).
     */
    function patchRender(plugin) {
        var P = plugin && plugin.Constructor && plugin.Constructor.prototype;
        if (!P || typeof P.render !== 'function' || P.render.__ssFast) return;
        if (typeof P.setDisabled !== 'function' || typeof P.setSelected !== 'function'
            || typeof P.findLis !== 'function') return;          // not 1.6.2's shape: leave that render alone
        var original = P.render;
        var fast = function (updateLi) {
            if (updateLi !== false) syncRows(this);
            return original.call(this, false);
        };
        fast.__ssFast = true;
        fast.__ssOriginal = original;
        P.render = fast;
    }

    /** The per-option loop of 1.6.2's render(), from one index instead of one full-row search per option. */
    function syncRows(inst) {
        inst.findLis();
        var lis = inst.$lis, byIndex = {};
        for (var i = 0; i < lis.length; i++) {
            var k = lis[i].getAttribute('data-original-index');
            if (k !== null) (byIndex[k] || (byIndex[k] = [])).push(lis[i]);
        }
        var parents = [], parentDisabled = [];                    // a handful of <optgroup>s at most
        inst.$element.find('option').each(function (index) {
            var rows = byIndex[index];
            if (!rows) return;                                    // no row: the library's filter() matched nothing
            var p = this.parentNode, at = parents.indexOf(p);
            if (at < 0) { at = parents.push(p) - 1; parentDisabled[at] = $(p).is(':disabled'); }
            var disabled = $(this).is(':disabled') || parentDisabled[at];
            var selected = $(this).is(':selected');
            for (var r = 0; r < rows.length; r++) paintRow(rows[r], disabled, selected);
        });
    }

    /** Exactly setDisabled(i, disabled) then setSelected(i, selected), for one row. */
    function paintRow(li, disabled, selected) {
        var $li = $(li);
        if (disabled) $li.addClass('disabled').find('a').attr('href', '#').attr('tabindex', -1);
        else $li.removeClass('disabled').find('a').removeAttr('href').attr('tabindex', 0);
        $li.toggleClass('selected', selected);
    }

    /** Redraw the button and the rows' state — never the rows themselves. checkDisabled() is what applies the SELECT's
     *  own disabled look in 1.6.2 (only refresh() used to call it), so a repaint always runs it. */
    function repaintOne(el, $s, st) {
        var inst = $s.data('selectpicker');
        st.stateChanged = false;
        try { if (inst && inst.checkDisabled) inst.checkDisabled(); } catch (e) {}
        st.lastVal = valueKey(el);
        try { $s.selectpicker('render'); } catch (e) {}
    }

    /**
     * ⭐ PSEL-1 F2/F3 — redraw a picker whose SELECTION or DISABLED STATE changed, WITHOUT rebuilding its rows.
     *
     * For the callers that used `selectpicker('refresh')` only to show a cleared or locked picker: main.js's form-reset
     * handler, updateReadOnly and resetBSDD, and business.js's invoice-edit lock/unlock (through main.js's
     * repaintPicker). Each rebuilt every row — a cart add or an Esc paid it two or three times over.
     *
     * Still a full refresh — exactly what the caller used to get — when:
     *   the <select> has no instance yet     (refresh constructs it, as it always did)
     *   it is untracked (no MutationObserver) or its OPTIONS changed (dirty)
     * and QUEUED change records are folded in first (sync): the observer reports on a microtask, and a caller that
     * appended an option one line earlier must still get its rebuild.
     *
     * @param sel  a <select> id (with or without '#'), element, or jQuery set
     */
    function repaintSearchableSelect(sel) {
        var $set = (typeof sel === 'string') ? $(sel.charAt(0) === '#' ? sel : '#' + sel) : $(sel);
        $set.each(function () {
            var el = this, $s = $(el);
            if (el.tagName !== 'SELECT') return;
            if (!$s.data('selectpicker')) { try { $s.selectpicker('refresh'); } catch (e) {} return; }
            var st = sync(el);
            if (!st || st.dirty) {
                try { $s.selectpicker('refresh'); } catch (e) {}
                markClean(el);
                return;
            }
            repaintOne(el, $s, st);
        });
    }

    window.repaintSearchableSelect = repaintSearchableSelect;

    /**
     * Initialise (or refresh) every eligible <select> on the page.
     * Safe to call repeatedly — that is how AJAX-populated dropdowns stay in sync.
     */
    function applySearchableSelects(root) {
        var $scope = root ? $(root) : $(document);
        $scope.find('select').each(function () {
            var $s = $(this);
            if (shouldSkip($s)) return;

            // Only destroy a REAL instance — see the destroy trap above.
            if ($s.data('selectpicker')) {
                try { $s.selectpicker('destroy'); } catch (e) {}
            }

            $s.addClass('selectpicker')
              .attr('data-size', '8')
              .attr('data-style', 'btn-default');

            $s.attr('data-live-search', 'true');

            if (this.multiple) {
                $s.attr('data-actions-box', 'true')
                  .attr('data-selected-text-format', 'count > 2');
            }
            if (!$s.attr('title')) $s.attr('title', 'Select…');
        });

        try { $scope.find('.selectpicker').selectpicker(); } catch (e) {}
        // Freshly built widgets match their options: start watching them CLEAN.
        $scope.find('.selectpicker').each(function () {
            if (this.tagName !== 'SELECT') return;
            watch(this, false);
            markClean(this);
        });
    }

    window.applySearchableSelects = applySearchableSelects;

    /**
     * Never touch a picker the operator is USING — see the long note on the ajaxComplete hook below for
     * what refreshing an open picker does to a cashier mid-selection.
     *
     * ⚠ "Using" means the menu is OPEN, or focus is INSIDE THE MENU (its live-search box, a row). It does NOT
     * mean focus on the CLOSED picker's button. refresh() rebuilds the menu's rows (reloadLi) and rewrites the
     * button's label (render); the button element, and the focus on it, survive both.
     *
     * Counting the button was a real defect: New Sale puts focus on #sellCustomerDD's button (the customer-first
     * entry point), so the picker was "busy" from the moment the screen opened. Its refresh was deferred to
     * `hidden.bs.dropdown` — which never fires for a menu that was never opened — and the cashier looked at
     * 1,615 customers in the <select> and ONE row in the list for as long as the screen stayed open (measured,
     * 33 s). A customer set by code (an invoice opened for edit) was never drawn on the button either.
     */
    function isBusy($bs) {
        if (!$bs.length) return false;
        if ($bs.hasClass('open')) return true;
        var menu = $bs[0].querySelector ? $bs[0].querySelector('.dropdown-menu') : null;
        return !!(menu && menu.contains && menu.contains(document.activeElement));
    }

    /**
     * Is the widget laid out at all? A picker on a screen that is not showing (display:none somewhere above it)
     * has no boxes. No widget found → treat as shown, so nothing is deferred that cannot be brought back.
     */
    function isShown($bs) {
        var bs = $bs[0];
        return !bs || !bs.getClientRects || bs.getClientRects().length > 0;
    }

    /*
     * ── Rebuild what can be SEEN; the rest when it comes on screen ───────────────────────────────────────
     *
     * One bootstrap-select 1.6.2 refresh of a big list costs seconds on its own: it rebuilds every row and then
     * liHeight() clones the whole menu into <body> to measure one row (data-size="8"). Measured on the first
     * business-dashboard load: the report filter rail's #rfCustomer (1,615 options) 3,224 ms and #rfProduct
     * (1,857) 2,685 ms — both on a screen nobody had opened. Those two were the whole of the remaining freeze.
     *
     * So a changed picker on a HIDDEN screen is not rebuilt now. Its label is redrawn (render(false) — the button
     * text only, no rows), it stays dirty, and its widget is watched; it is rebuilt when:
     *   - it comes on screen (IntersectionObserver → a pass), or
     *   - its menu is about to open (show.bs.dropdown — the backstop, and the only trigger on an engine with no
     *     IntersectionObserver), or
     *   - any later pass finds it shown.
     * Nothing a user can see is left stale: a hidden list is not being looked at, and an opening one is rebuilt
     * before it shows.
     */
    var IO = window.IntersectionObserver;
    var io = IO ? new IO(function (entries) {
        var any = false;
        for (var i = 0; i < entries.length; i++) {
            if (!entries[i].isIntersecting) continue;
            var target = entries[i].target, owner = target.__ssOwner;
            io.unobserve(target);
            if (owner && owner.__ssWatch) owner.__ssWatch.io = false;
            any = true;
        }
        if (any) schedulePass();
    }) : null;

    function deferUntilShown(el, $bs) {
        var st = el.__ssWatch, inst = $(el).data('selectpicker');
        try { if (inst && inst.render) inst.render(false); } catch (e) {}   // the label only — no rows
        st.lastVal = valueKey(el);
        if (io && !st.io && $bs[0]) {
            $bs[0].__ssOwner = el;
            st.io = true;
            io.observe($bs[0]);
        }
    }

    /**
     * Refresh ONE picker, honouring the busy guard — deferring to `hidden.bs.dropdown` if it is open.
     *
     * <p>Exposed because of a trap that pairs with background loading. The ajaxComplete hook below is what
     * keeps AJAX-populated pickers in sync, and several populate helpers rely on it instead of refreshing
     * themselves. But a background read is sent with jQuery's {@code global: false}, which excludes it from
     * <b>every</b> global AJAX handler — {@code ajaxComplete} included, not just the overlay's
     * ajaxStart/ajaxStop. So the moment a picker's loader stops blocking the UI, that hook stops firing for
     * it: the &lt;option&gt;s land in the DOM and the widget never redraws, leaving a cashier looking at an
     * empty "Select Customer" that will never fill.
     *
     * <p>A background loader must therefore refresh explicitly — and must do it THROUGH here rather than
     * calling {@code selectpicker('refresh')} inline, or the busy guard exists in one code path and not the
     * other, which is the bug it was written to prevent.
     *
     * <p>⚠ UNCONDITIONAL on purpose: an explicit call is a caller saying "I changed this". It does NOT consult
     * the change tracking below — those callers are exactly the ones the ajaxComplete pass never hears about.
     *
     * @param sel  a <select> id, element, or jQuery object
     */
    function refreshSearchableSelect(sel) {
        var $s = (typeof sel === 'string') ? $('#' + sel) : $(sel);
        if (!$s.length || !$s.data('selectpicker')) return;
        var $bs = $s.next('.bootstrap-select');
        if (isBusy($bs)) { $bs.attr('data-ss-stale', '1'); return; }
        try { $s.selectpicker('refresh'); } catch (e) {}
        markClean($s[0]);
    }

    window.refreshSearchableSelect = refreshSearchableSelect;

    /**
     * ⭐ THE PASS the ajaxComplete hook runs — only what CHANGED, and can be SEEN, is redrawn.
     *
     * <h3>What this replaced, measured</h3>
     * The hook used to refresh EVERY `.selectpicker` (~48 on business) on EVERY ajaxComplete. bootstrap-select's
     * refresh() rebuilds the whole list and re-reads every option's attributes, and the product and customer
     * pickers hold thousands. A CPU profile of the business dashboard's first load (2026-09-14) put this hook at
     * <b>39.8 s of 52.6 s</b>, in four main-thread blocks of 8.4, 5.8, 5.2 and 13.2 s — the "never went quiet"
     * beforeEach timeouts that failed the BLK-2, BLK-3 and BLK-4 gates, and a frozen dashboard for anyone whose
     * catalogue has grown. Nothing was wrong with the options; they were simply redrawn over and over.
     *
     * <h3>Now</h3>
     *   options changed, picker shown    → refresh    — rebuild the list; ONE per task, the rest next task
     *   options changed, picker hidden   → label only — rebuilt when it comes on screen (deferUntilShown)
     *   only the selection changed       → render     — redraw the button; the list is untouched
     *   nothing changed                  → nothing
     *   no MutationObserver (old engine) → refresh    — exactly the old behaviour
     * and the busy guard is unchanged: an open picker is marked stale and refreshed when it closes.
     *
     * <h3>Why one rebuild per task</h3>
     * A burst of completions is coalesced into one pass, which is right for cheap work and wrong for expensive
     * work: several multi-second rebuilds in one pass became ONE block of their sum (8.2 s, measured). Handing
     * the remaining rebuilds to the next task lets a keystroke or a click in between be answered.
     */
    function runPass() {
        passPending = false;
        var rebuilt = false, more = false;
        $('.selectpicker').each(function () {
            var el = this;
            if (el.tagName !== 'SELECT') return;
            var $s = $(el);
            if (!$s.data('selectpicker')) return;

            // A picker built by someone else's selectpicker() call, never seen here: one refresh to start clean.
            var st = el.__ssWatch || watch(el, true);
            if (!st) { refreshSearchableSelect($s); return; }

            var $bs = $s.next('.bootstrap-select');
            if (st.dirty) {
                if (isBusy($bs)) { $bs.attr('data-ss-stale', '1'); return; }   // refreshed on close
                if (!isShown($bs)) { deferUntilShown(el, $bs); return; }        // rebuilt when it is seen
                if (rebuilt) { more = true; return; }                            // next task
                try { $s.selectpicker('refresh'); } catch (e) {}
                markClean(el);
                rebuilt = true;
                return;
            }
            var v = valueKey(el);
            // PSEL-1: a SELECT-level disabled toggle (stateChanged) needs the same repaint as a new selection.
            if (v !== st.lastVal || st.stateChanged) {
                // Busy FIRST. Recording the new value before this check meant a .val() made by CODE while the
                // picker was open advanced lastVal with nothing drawn and nothing marked — after close the widget
                // kept the old selection until its options next changed (caught in review). Mark it stale instead:
                // the close handler refreshes it and records the value.
                if (isBusy($bs)) { $bs.attr('data-ss-stale', '1'); return; }
                repaintOne(el, $s, st);
            }
        });
        if (more) schedulePass();
    }

    var passPending = false;
    /** A burst of completions is ONE pass on the next tick, not one per request. */
    function schedulePass() {
        if (passPending) return;
        passPending = true;
        window.setTimeout(runPass, 0);
    }

    $(function () {
        applySearchableSelects();

        // Most of these dropdowns are filled by AJAX AFTER load, and several populate helpers append
        // <option>s without calling refresh themselves. One ajaxComplete hook keeps every one in sync
        // instead of each helper having to remember.
        // REFRESH ONLY — never a full re-init here. Re-running the initialiser on every AJAX response
        // would destroy and rebuild all ~48 pickers each time, closing whatever the user had open.
        //
        // ...and REFRESH DOES THE SAME THING to the one picker that matters. bootstrap-select's
        // refresh() calls reloadLi(), which rebuilds the option list: an open menu closes, a half-typed
        // search is wiped, and focus falls out of the destroyed subtree onto <body>. The guard above
        // was written against the wrong half of the risk.
        //
        // It is not theoretical. The sale screen keeps a poll running while it is open, so this fires
        // repeatedly with a picker open in front of the cashier — the customer list shuts by itself
        // mid-selection. It is also what made the checkout keyboard spec unrepeatable: five runs of
        // identical code gave 6, 3, 5, 2 and 6 passes, a different test failing each time, because
        // whether a keystroke landed depended on whether a poll had just returned.
        //
        // So: never touch a picker the operator is USING. Refresh it when they close it instead — the
        // options cannot be stale on screen, because the screen is not showing them.
        // ⚠ This fires only for requests that participate in jQuery's global AJAX events. A loader that
        // uses `global: false` to stay off the blocking overlay is excluded from THIS hook too, and must
        // call refreshSearchableSelect() itself — see that function for the full trap.
        // ⭐ And it now redraws only what CHANGED — see runPass() for the 39.8 s this used to cost.
        $(document).ajaxComplete(schedulePass);

        // The deferred half. Bootstrap 3 fires this on the dropdown's parent when the menu closes.
        $(document).on('hidden.bs.dropdown', '.bootstrap-select', function () {
            var $bs = $(this);
            if (!$bs.attr('data-ss-stale')) return;
            $bs.removeAttr('data-ss-stale');
            var $s = $bs.prev('select');
            try { $s.selectpicker('refresh'); } catch (e) {}
            if ($s[0]) markClean($s[0]);
        });

        // The backstop for deferUntilShown: a picker still dirty when its menu is ABOUT to open is rebuilt first.
        // Bootstrap 3 fires this on the same parent, before the menu is shown — nothing is open and no search has
        // been typed yet, so the rebuild cannot close or wipe anything.
        $(document).on('show.bs.dropdown', '.bootstrap-select', function () {
            var $s = $(this).prev('select'), el = $s[0];
            var st = el && el.__ssWatch;
            if (!st || !st.dirty) return;
            try { $s.selectpicker('refresh'); } catch (e) {}
            markClean(el);
        });
    });
})(jQuery);
